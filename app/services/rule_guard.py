"""규칙 기반 안전장치 (SPEC 2.10.3)

링크·번호 없이 답장·전화를 유도하는 수법을 LLM과 별개로 잡는다.
고정 표현 조합이 문자에 모두 있으면 규칙 이름을 돌려준다. 결과는 RISK 근거로만 쓰고 SAFE를 만들지 않는다.
목록 변경은 SPEC 변경으로 승인받는다. 새로운 표현은 잡지 못한다.
"""

import re
import unicodedata

# 규칙 이름 → 모두 충족해야 하는 표현 묶음. 각 묶음에서 하나 이상 포함되면 충족이다.
# 비교는 NFKC 정규화·공백 제거·영문 소문자화 후 포함 여부로 하므로 표현에도 공백을 넣지 않는다.
RULES: dict[str, tuple[tuple[str, ...], ...]] = {
    "가족 사칭": (
        ("엄마", "아빠", "어머니", "아버지", "딸", "아들", "언니", "누나", "오빠", "동생"),
        ("액정", "폰고장", "폰이고장", "폰깨", "폰이깨", "고장나", "수리맡", "번호바뀌", "번호변경",
         "새번호", "임시폰", "폰분실", "폰잃어"),
        ("문자줘", "문자해", "문자주", "톡줘", "톡해", "톡주", "연락줘", "연락해", "연락주", "답장", "이번호로"),
    ),
    "기관 연락 유도": (
        ("검찰", "지검", "경찰", "금감원", "금융감독원", "수사관", "금융위원회"),
        ("연루", "도용", "범죄", "계좌정지", "대포통장", "피의자"),
        ("연락바", "연락주", "연락요망", "전화바", "전화주", "전화요망", "연락하시", "전화하시", "출석"),
    ),
    "카드·결제 확인 유도": (
        ("카드", "결제", "발급"),
        ("본인이아닐", "본인신청이아닐", "본인이아니", "신청하지않", "본인결제가아닐", "본인이사용하지"),
        ("고객센터", "전화", "연락", "문의"),
    ),
}

_WHITESPACE = re.compile(r"\s+")


def _compact(text: str) -> str:
    return _WHITESPACE.sub("", unicodedata.normalize("NFKC", text)).lower()


def match_rules(message: str) -> list[str]:
    """일치한 규칙 이름을 정의 순서대로 돌려준다."""
    text = _compact(message)
    return [
        name for name, groups in RULES.items()
        if all(any(word in text for word in group) for group in groups)
    ]
